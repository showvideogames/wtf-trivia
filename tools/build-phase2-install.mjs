#!/usr/bin/env node
/**
 * Assemble the HOSTED Phase 2 install file from the migrations, so the two
 * can never drift: supabase/ops/hosted/phase2-install.sql = the account
 * layer of 0001 (sections B–G; section A, the live schema, is deliberately
 * left out because the hosted project already has every one of those
 * objects and content must never be recreated) + 0002 (the player-table
 * lockdown) + the migration-ledger rows, all meant to run in ONE transaction
 * through `node tools/hosted.mjs sql --file supabase/ops/hosted/phase2-install.sql`.
 *
 * 0003 (the admin gate) is NOT included: it is applied on its own, later,
 * once an admin account exists (tools/hosted.mjs refuses it otherwise).
 *
 * Also writes supabase/ops/hosted/live-replica.sql = section A alone, the
 * live schema as declared, for the local rehearsal (tools/rehearse-local.mjs).
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(path.join(ROOT, p), "utf8").replace(/\r\n/g, "\n");
const m1 = read("supabase/migrations/0001_wtf_baseline.sql");
const m2 = read("supabase/migrations/0002_wtf_player_lockdown.sql");

const A_START = "-- ============================================================================\n-- A. THE LIVE SCHEMA";
const B_START = "-- ============================================================================\n-- B. THE LOCAL ACCOUNT";
const a = m1.indexOf(A_START);
const b = m1.indexOf(B_START);
if (a < 0 || b < 0 || b < a) throw new Error("section markers not found in 0001");

const header = (title, body) => `-- ============================================================================
--  ${title}
-- ============================================================================
--  GENERATED by tools/build-phase2-install.mjs from supabase/migrations/.
--  Do not edit by hand: edit the migrations and rebuild.
--  Built ${new Date().toISOString()}.
${body}`;

const sectionA = m1.slice(a, b);
const accountLayer = m1.slice(b);

const install = header("WTF Trivia: HOSTED PHASE 2 INSTALL (one transaction; additive; content untouched)", `--
--  Runs through: node tools/hosted.mjs sql --file supabase/ops/hosted/phase2-install.sql
--  (rehearsal inside BEGIN … ROLLBACK by default; --apply commits). The tool
--  fingerprints every games row before and after and reports any movement.
--
--  Contents:
--    1. the account layer of 0001 (sections B–G): accounts, wtf_uid(),
--       account_email(), ensure_account(), my_account(), ping(), admins,
--       is_wtf_admin(), best_combo(), recompute_player_stats(),
--       guest_handoffs + offer/resolve/import/decline, delete_*_account, grants
--    2. 0002: the player-table lockdown (drops the permissive duplicate
--       policies; explicit grants on the player tables)
--    3. the migration ledger rows 0001 and 0002, so \`supabase db push\`
--       and \`supabase migration list\` agree with the repository afterwards
--
--  NOT here: section A of 0001 (the live schema: the hosted project already
--  has it, and content is never recreated) and 0003 (the admin gate; applied
--  later, on its own, once an admin account exists).
--
--  Pre-condition checked below: the live tables exist with the expected
--  keys (ids are text; plays key on puzzle_id), and none of the new objects
--  exist yet.
-- ============================================================================

do $$
begin
  if to_regclass('public.games') is null or to_regclass('public.players') is null or to_regclass('public.game_records') is null then
    raise exception 'phase2-install aborted: the live tables are missing; this is not the WTF project';
  end if;
  if (select udt_name from information_schema.columns where table_schema='public' and table_name='games' and column_name='id') <> 'text' then
    raise exception 'phase2-install aborted: games.id is not text; the live shape differs from the inventory';
  end if;
  if not exists (select 1 from information_schema.columns where table_schema='public' and table_name='game_records' and column_name='puzzle_id') then
    raise exception 'phase2-install aborted: game_records.puzzle_id is missing; the puzzle-id cutover is not in place';
  end if;
  if to_regclass('public.accounts') is not null or to_regclass('public.guest_handoffs') is not null or to_regclass('public.admins') is not null then
    raise exception 'phase2-install aborted: the account layer already exists';
  end if;
end $$;

create extension if not exists pgcrypto with schema extensions;

-- ---------------------------------------------------------------------------
-- 1. 0001_wtf_baseline.sql, sections B–G
-- ---------------------------------------------------------------------------
${accountLayer}

-- ---------------------------------------------------------------------------
-- 2. 0002_wtf_player_lockdown.sql
-- ---------------------------------------------------------------------------
${m2}

-- ---------------------------------------------------------------------------
-- 3. the migration ledger (what \`supabase db push\` would have written)
-- ---------------------------------------------------------------------------
create schema if not exists supabase_migrations;
create table if not exists supabase_migrations.schema_migrations (
  version text primary key,
  statements text[],
  name text
);
insert into supabase_migrations.schema_migrations (version, name)
values ('0001', 'wtf_baseline'), ('0002', 'wtf_player_lockdown')
on conflict (version) do nothing;
`);

const replica = header("WTF Trivia: the LIVE schema as declared (section A of 0001), for the local rehearsal only", `--
--  tools/rehearse-local.mjs applies this to a blank local database (with the
--  hosted project's default privileges re-created), loads a hosted content
--  export, then runs phase2-install.sql and proves the content fingerprint
--  did not move. Never run against the hosted project: it already is this.
-- ============================================================================

create extension if not exists pgcrypto with schema extensions;

${sectionA}`);

mkdirSync(path.join(ROOT, "supabase", "ops", "hosted"), { recursive: true });
writeFileSync(path.join(ROOT, "supabase", "ops", "hosted", "phase2-install.sql"), install);
writeFileSync(path.join(ROOT, "supabase", "ops", "hosted", "live-replica.sql"), replica);
console.log(`wrote supabase/ops/hosted/phase2-install.sql (${install.length} chars) and live-replica.sql (${replica.length} chars)`);
